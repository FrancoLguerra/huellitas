package ar.com.huellitas.sessions;

public class InfoSession {
	private String nombre;
	private String apellido;
	private String mail;
	private String telefono;
	
	
	public InfoSession(String nombre, String apellido, String mail, String telefono) {
		super();
		this.nombre = nombre;
		this.apellido = apellido;
		this.mail = mail;
		this.telefono = telefono;
	}
	
	
}
